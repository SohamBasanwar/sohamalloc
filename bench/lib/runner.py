def system_lib(stem):
    """Newest installed soname of a system allocator, e.g. libmimalloc.so.3
    on Ubuntu 26.04 and libmimalloc.so.2 on 24.04; LIB_<NAME> overrides."""
    env = os.environ.get("LIB_" + stem.upper().replace("LIB", "", 1))
    if env:
        return env
    cands = [p for p in glob.glob(os.path.join(LIBDIR, stem + ".so.*"))
             if re.fullmatch(r".*\.so\.[0-9]+", p)]
    if not cands:
        return os.path.join(LIBDIR, stem + ".so")
    return max(cands, key=lambda p: int(p.rsplit(".", 1)[1]))


ALLOCATORS = {
    "glibc": None,
    "jemalloc": system_lib("libjemalloc"),
    "mimalloc": system_lib("libmimalloc"),
    "tcmalloc": system_lib("libtcmalloc_minimal"),
    "sohamalloc": os.environ.get("SOHAM_LIB", ROOT + "/build/libsohamalloc.so"),
}

CSV_FIELDS = ["stamp", "rep", "bench", "alloc", "status", "time_s", "wall_s",
              "rss_kb", "user_s", "sys_s", "metric", "detail"]


# ------------------------------------------------------------------ metrics
# Fixed-duration benchmarks report throughput; like mimalloc-bench we turn it
# into a "relative time" (lower is better) so every benchmark reads the same.
def m_larson(out):
    m = re.search(r"relative time: ([0-9.]+)s", out)
    return float(m.group(1)) if m else None


def m_xmalloc(out):
    m = re.search(r"rtime: ([0-9.]+)", out)
    return float(m.group(1)) if m else None


def m_rptest(out):
    m = re.search(r"\.\.\.([0-9]+) memory ops", out)
    return 2000000.0 / int(m.group(1)) if m and int(m.group(1)) > 0 else None


def m_glibc_thread(out):
    m = re.search(r"^([0-9]+) iterations", out, re.M)
    return 1e9 / int(m.group(1)) if m and int(m.group(1)) > 0 else None


# ------------------------------------------------------------------ table
class Bench:
    def __init__(self, name, argv, quick=None, cwd=MB, stdin=None, metric=None,
                 digest=None, env=None, needs=None, timeout=180, kind="mb", quick_stdin=None,
                 expect=None, in_tmp=False):
        self.name, self.argv, self.quick = name, argv, quick
        self.quick_stdin = quick_stdin
        self.expect = expect   # regex that must occur in stdout for the run to count
        self.in_tmp = in_tmp   # run in a scratch directory (the program writes files)
        self.cwd, self.stdin, self.metric = cwd, stdin, metric
        self.digest = digest   # None | "stdout" | path-of-output-file (fmt with {tmp})
        self.env = env or {}
        self.needs = needs or [argv[0] if argv[0].startswith("/") else os.path.join(cwd, argv[0])]
        self.timeout, self.kind = timeout, kind


