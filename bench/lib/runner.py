#!/usr/bin/env python3
"""sohamalloc benchmark runner (entry point: bench/run_bench.sh).

For every repetition, for every benchmark, run every allocator once (the
allocator order is rotated per repetition and benchmark so that no allocator
always runs first or last).  Each run is wrapped in GNU time
(`/usr/bin/time -f '%e %M %U %S'`) and the allocator is injected with
`env LD_PRELOAD=<lib>` so that only the benchmark process tree, not the
measuring tools, uses it.

Results: bench/out/results-<stamp>.csv (one row per run) and
bench/out/report.md (+ report-<stamp>.md), generated by report.py.
"""
